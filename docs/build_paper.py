def run_font(run, cn="宋体", size=12, bold=False, en="Times New Roman", color=None):
    run.font.name = en
    run._element.get_or_add_rPr().rFonts.set(qn("w:eastAsia"), cn)
    run.font.size = Pt(size)
    run.bold = bold
    if color:
        run.font.color.rgb = RGBColor(*color)
    return run


def para(text="", cn="宋体", size=12, bold=False, align=None, indent=0,
         space_before=0, space_after=0, line=1.5, en="Times New Roman"):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.line_spacing = line
    pf.space_before = Pt(space_before)
    pf.space_after = Pt(space_after)
    if indent:
        pf.first_line_indent = Pt(size * indent)
    if align is not None:
        p.alignment = align
    if text:
        run_font(p.add_run(text), cn, size, bold, en)
    return p


